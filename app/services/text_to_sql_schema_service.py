def allowed_table_names() -> set[str]:
    return set(ALLOWED_TABLES)


def allowed_columns_by_table() -> dict[str, set[str]]:
    return {name: set(schema.columns) for name, schema in ALLOWED_TABLES.items()}


def build_schema_prompt() -> str:
    lines = [
        "Allowed Odoo PostgreSQL schema:",
        "Only use these tables and columns.",
    ]
    for table in ALLOWED_TABLES.values():
        lines.append(f"- {table.name}: {', '.join(table.columns)}. {table.description}")
    lines.extend(
        [
            "Required joins:",
            "- sale_order.partner_id = res_partner.id",
            "- sale_order.company_id = res_company.id",
            "- sale_order.currency_id = res_currency.id",
            "- sale_order.warehouse_id = stock_warehouse.id",
            "- sale_order_line.order_id = sale_order.id",
            "- sale_order_line.product_id = product_product.id",
            "- sale_order_line.product_uom = uom_uom.id",
            "- product_product.product_tmpl_id = product_template.id",
            "- product_template.categ_id = product_category.id",
            "- account_move.partner_id = res_partner.id",
            "- account_move.company_id = res_company.id",
            "- account_move.currency_id = res_currency.id",
            "- account_move_line.move_id = account_move.id",
            "- account_move_line.product_id = product_product.id",
            "- account_move_line.product_uom_id = uom_uom.id",
            "- purchase_order.partner_id = res_partner.id",
            "- purchase_order.company_id = res_company.id",
            "- purchase_order.currency_id = res_currency.id",
            "- purchase_order_line.order_id = purchase_order.id",
            "- purchase_order_line.product_id = product_product.id",
            "- purchase_order_line.product_uom = uom_uom.id",
            "- stock_quant.product_id = product_product.id",
            "- stock_quant.location_id = stock_location.id",
            "- stock_quant.company_id = res_company.id",
            "- stock_move.product_id = product_product.id",
            "- stock_move.location_id = stock_location.id",
            "- stock_move.location_dest_id = stock_location.id",
            "- stock_move.warehouse_id = stock_warehouse.id",
            "- stock_move.sale_line_id = sale_order_line.id",
            "- stock_move.purchase_line_id = purchase_order_line.id",
            "Common filters:",
            "- Sales revenue: sale_order.state IN ('sale', 'done') or sale_order_line.state IN ('sale', 'done').",
            "- Posted customer invoices: account_move.state='posted' AND account_move.move_type='out_invoice'.",
            "- Posted vendor bills: account_move.state='posted' AND account_move.move_type='in_invoice'.",
            "- Stock on hand: stock_location.usage='internal' and stock_quant.quantity > 0.",
            "- Completed stock movements: stock_move.state='done'.",
            "- Product/invoice/order line analytics should usually filter display_type IS NULL.",
            "- JSONB translated names: product_template.name and uom_uom.name need COALESCE(name->>'en_US', name::text).",
            "SQL rules:",
            "- Generate PostgreSQL only.",
            "- Generate one read-only SELECT statement, optionally with CTEs.",
            "- Always include a LIMIT no greater than the configured maximum.",
            "- Never use INSERT, UPDATE, DELETE, DROP, ALTER, COPY, CALL, DO, temp tables, or DDL.",
        ]
    )
    return "\n".join(lines)
